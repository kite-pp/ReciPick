-- 1. 프로필 테이블
CREATE TABLE public.profiles (
  id UUID REFERENCES auth.users ON DELETE CASCADE PRIMARY KEY,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  username TEXT,
  avatar_url TEXT NULL,
  notify_expiry BOOLEAN NOT NULL DEFAULT TRUE,     -- 소비기한 임박 알림
  notify_recommend BOOLEAN NOT NULL DEFAULT FALSE, -- 맞춤 추천 알림
  notify_shopping BOOLEAN NOT NULL DEFAULT FALSE   -- 장보기 리마인드 알림

);

-- 2. 냉장고 식재료 테이블
CREATE TABLE public.fridge_items (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 냉장고 내부 항목의 id
  user_id UUID REFERENCES auth.users ON DELETE CASCADE NOT NULL,
  ingredient_id INT NOT NULL, -- 식재료 id
  amount TEXT,
  expires_at DATE, -- 유통기한
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 3. 찜한 레시피 테이블
CREATE TABLE public.favorites (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users ON DELETE CASCADE NOT NULL,
  recipe_id INT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  UNIQUE(user_id, recipe_id)
);

-- 4. 최근 본 레시피 테이블
CREATE TABLE public.recent_recipes (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users ON DELETE CASCADE NOT NULL,
  recipe_id INT NOT NULL,
  viewed_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 5. 장보기 목록 테이블
CREATE TABLE public.shopping_items (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users ON DELETE CASCADE NOT NULL,
  ingredient_id INT NOT NULL,
  checked BOOLEAN DEFAULT FALSE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 6. 알림 이력 테이블 (중복 알림 방지용)
CREATE TABLE public.notification_logs (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users ON DELETE CASCADE NOT NULL,
  fridge_item_id INT REFERENCES public.fridge_items ON DELETE CASCADE NOT NULL,
  notification_type TEXT NOT NULL, -- 'D-7', 'D-DAY', 'EXPIRED'
  notified_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- RLS (Row Level Security) 활성화 및 정책 설정 (본인만 CRUD)
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Users can manage their own profile" ON public.profiles
  FOR ALL TO authenticated                               
  USING ((select auth.uid()) = id)                       
  WITH CHECK ((select auth.uid()) = id);                 

