-- 1. 프로필 테이블
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID REFERENCES auth.users ON DELETE CASCADE PRIMARY KEY,
  updated_at TIMESTAMPTZ DEFAULT NOW(),
  nickname TEXT NULL,
  preferred_categories TEXT[] NOT NULL DEFAULT '{}',
  excluded_ingredient_ids INT[] NOT NULL DEFAULT '{}',
  notify_expiry BOOLEAN NOT NULL DEFAULT TRUE,
  notify_recommend BOOLEAN NOT NULL DEFAULT FALSE,
  notify_shopping BOOLEAN NOT NULL DEFAULT FALSE
);

-- 2. 냉장고 식재료 테이블
CREATE TABLE IF NOT EXISTS public.fridge_items (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users ON DELETE CASCADE NOT NULL,
  ingredient_id INT NOT NULL,
  quantity NUMERIC NULL CHECK (quantity >= 0),
  unit TEXT NULL,
  expires_at DATE NULL,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE (user_id, ingredient_id)
);

-- 3. 찜한 레시피 테이블
CREATE TABLE IF NOT EXISTS public.favorites (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users ON DELETE CASCADE NOT NULL,
  recipe_id INT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE (user_id, recipe_id)
);

-- 4. 최근 본 레시피 테이블
CREATE TABLE IF NOT EXISTS public.recent_recipes (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users ON DELETE CASCADE NOT NULL,
  recipe_id INT NOT NULL,
  viewed_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE (user_id, recipe_id)
);

-- 5. 장보기 목록 테이블
CREATE TABLE IF NOT EXISTS public.shopping_items (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users ON DELETE CASCADE NOT NULL,
  ingredient_id INT NOT NULL,
  checked BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE (user_id, ingredient_id)
);

-- 6. 알림 이력 테이블
CREATE TABLE IF NOT EXISTS public.notification_logs (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users ON DELETE CASCADE NOT NULL,
  fridge_item_id INT REFERENCES public.fridge_items ON DELETE CASCADE NULL,
  notification_type TEXT NOT NULL CHECK (notification_type IN ('D-7', 'D-DAY', 'EXPIRED')),
  notified_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE (fridge_item_id, notification_type)
);

-- 인덱스 생성
CREATE INDEX IF NOT EXISTS recent_recipes_user_viewed_idx
  ON public.recent_recipes (user_id, viewed_at DESC);
CREATE INDEX IF NOT EXISTS fridge_items_expires_at_idx
  ON public.fridge_items (expires_at);
CREATE INDEX IF NOT EXISTS notification_logs_user_id_idx
  ON public.notification_logs (user_id);

-- RLS: 프로필 테이블 본인 접근 권한
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Users can manage their own profile" ON public.profiles;
CREATE POLICY "Users can manage their own profile" ON public.profiles
  FOR ALL TO authenticated
  USING ((select auth.uid()) = id)
  WITH CHECK ((select auth.uid()) = id);

-- RLS: 사용자 데이터 테이블 동적 적용 (fridge_items, favorites, recent_recipes, shopping_items)
DO $$
DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY['fridge_items', 'favorites', 'recent_recipes', 'shopping_items'] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('DROP POLICY IF EXISTS "own rows" ON public.%I', t);
    EXECUTE format(
      'CREATE POLICY "own rows" ON public.%I
         FOR ALL TO authenticated
         USING ((select auth.uid()) = user_id)
         WITH CHECK ((select auth.uid()) = user_id)', t);
  END LOOP;
END $$;

-- RLS: 알림 이력 (조회 및 본인 INSERT 권한)
ALTER TABLE public.notification_logs ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Users can view their own notification logs" ON public.notification_logs;
DROP POLICY IF EXISTS "Users can insert their own notification logs" ON public.notification_logs;

CREATE POLICY "Users can view their own notification logs" ON public.notification_logs
  FOR SELECT TO authenticated 
  USING ((select auth.uid()) = user_id);

CREATE POLICY "Users can insert their own notification logs" ON public.notification_logs
  FOR INSERT TO authenticated 
  WITH CHECK ((select auth.uid()) = user_id);